def forecast_role(series, future_months=3):

    series = series.astype(float)

    # Convert months into sequential numbers
    X = np.arange(len(series)).reshape(-1, 1)

    # Monthly posting counts
    y = series.values

    # Train model
    model = LinearRegression()
    model.fit(X, y)

    # Create future month numbers
    future_X = np.arange(
        len(series),
        len(series) + future_months
    ).reshape(-1, 1)

    # Predict future demand
    predictions = model.predict(future_X)

    # Posting counts cannot be negative
    predictions = np.maximum(predictions, 0)

    return predictions

